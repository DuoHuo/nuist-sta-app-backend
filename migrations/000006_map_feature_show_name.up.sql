-- ---------------------------------------------------------------------------
-- 通用地物是否「在地图上标注名称」。
--
-- 起因：OSM 导入把绿地、水面、停车场这些面也变成了通用地物，而它们的名字
-- （尤其脚本自动生成的"绿地 3""停车场 7"）画到地图上只会盖住地图；
-- 但它们仍需在列表与详情页里可读——所以这是"标注开关"，不是"改名/删除"。
--
-- 默认 true：管理台手绘的地物是人主动命名的，默认标注；
-- 脚本导入的按来源决定（OSM 原名 → true，脚本生成的名字 → false）。
-- 与 kind 无关，逐条可控：绿地也能标、篮球场也能不标。
-- ---------------------------------------------------------------------------
ALTER TABLE map_features ADD COLUMN show_name BOOLEAN NOT NULL DEFAULT TRUE;
COMMENT ON COLUMN map_features.show_name IS '地图上是否标注名称；false=只在列表/详情页出现，不画文字标签';
